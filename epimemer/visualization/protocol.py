"""Wire protocol between an MCP session process and the visualization hub.

The hub (``hub.py``) is a relay + session registry; each MCP server process is a
*session* that dials out to the hub (``hub_client.py``), registers, publishes
events, and answers snapshot / graph-list RPCs against its own storage. These
Pydantic models are the messages exchanged over that ``/ingest`` socket — shared
by both sides so the shapes cannot drift.

The event payloads themselves are the existing ``events.py`` contract, carried
opaquely as JSON inside ``PublishEvent`` — this module adds only the envelope
and session identity around them.
"""

from datetime import UTC, datetime
from typing import Literal

from pydantic import BaseModel, Field

# The version of the wire contract: the messages in this module, the snapshot
# and embeddings payloads `snapshot.py` assembles, and the hub's HTTP routes.
# Removing or renaming a field, or changing what one means, bumps it. Adding a
# field does not, because a client reads the fields it knows and ignores the
# rest, so a client written for version N reads every payload that says N.
VIZ_SCHEMA_VERSION = 1

# What the hub reports for a session whose Register names no version: one
# started before the contract carried a number, so it speaks something older
# than version 1. Reported as a number rather than left out, so a client can
# compare it with the version it speaks without a missing-field case.
UNVERSIONED_SCHEMA = 0

# The largest message the ``/ingest`` socket carries, in bytes, in either
# direction. 16 MiB is uvicorn's default ``ws_max_size``; it is named here so
# the hub passes it to uvicorn and every session measures its answers against
# it, and neither side has to guess the other's limit. A message over it closes
# the socket with 1009, which takes the whole session off the hub, so a session
# replaces an answer that would not fit with an error saying so.
INGEST_MAX_MESSAGE_BYTES = 16 * 1024 * 1024


def _now() -> datetime:
    return datetime.now(UTC)


class SessionInfo(BaseModel):
    """Identity + current state of one MCP server process, as seen by the hub."""

    session_id: str  # uuid4, generated by the MCP process at startup
    pid: int
    backend: str  # storage.backend_name: "memory" | "surrealdb" | "sqlite" | "postgres"
    active_graph: str
    started_at: datetime = Field(default_factory=_now)


# --- session → hub ---


class Register(BaseModel):
    """First message a session sends on connect; re-sent when active_graph changes.

    ``schema_version`` is the contract this session speaks, which the hub
    lists beside the session so a client can tell before it asks for anything.
    """

    type: Literal["register"] = "register"
    info: SessionInfo
    schema_version: int = VIZ_SCHEMA_VERSION


def spoken_schema_version(register: Register) -> int:
    """The contract version a Register names, or ``UNVERSIONED_SCHEMA``.

    Read from the fields the sender set. Parsing a Register from a session that
    predates the field fills ``schema_version`` with today's default, which
    would list that session as speaking the current contract.
    """
    if "schema_version" in register.model_fields_set:
        return register.schema_version
    return UNVERSIONED_SCHEMA


class PublishEvent(BaseModel):
    """A visualization event to fan out to browsers.

    ``payload`` is a serialized ``events.py`` event, unmodified. The hub injects
    ``session_id`` into it before forwarding, so producers need not stamp it.
    """

    type: Literal["event"] = "event"
    payload: dict


class RpcResponse(BaseModel):
    """A session's answer to an ``RpcRequest`` (matched by ``request_id``)."""

    type: Literal["rpc_response"] = "rpc_response"
    request_id: str
    result: dict | None = None
    error: str | None = None


# --- hub → session ---


class RpcRequest(BaseModel):
    """A read the hub asks a session to execute in its own process.

    ``list_graphs`` takes no params; ``snapshot`` takes ``{"graph": <name>}``;
    ``retrievals`` takes none and answers with this session's own retrieval
    records, payloads included — the route that keeps working when the hub
    holds structural metadata only (`RETRIEVAL_PROVENANCE.md` §3.2).
    ``warnings`` takes none and answers with what the active graph does about
    advisories, in the shape ``configure_warnings`` returns; it is a read, and
    nothing on the dashboard writes a setting (`EVENT_LOG.md` §12.4).
    ``embeddings`` takes ``{"graph": <name>, "node_type": "topic" | "fact" |
    "inference" | None}`` and answers with the vectors of that graph's active
    nodes, of that type when one is named (``snapshot.assemble_embeddings``).
    """

    type: Literal["rpc_request"] = "rpc_request"
    request_id: str
    method: Literal["list_graphs", "snapshot", "retrievals", "warnings", "embeddings"]
    params: dict = Field(default_factory=dict)


# Discriminated by the ``type`` field on parse.
SessionMessage = Register | PublishEvent | RpcResponse
HubMessage = RpcRequest
